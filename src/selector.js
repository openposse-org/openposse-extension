// Computing a durable CSS selector for one element.
//
// Promoted here from `tools/capture.js`, which was the hand-cranked precursor to the recorder
// and is now built from this module – one implementation, so the selector a user records
// through the wizard is the same one the DevTools tool reports. Two copies would drift, and the
// symptom would be a recipe that works when captured by hand and not by the product.
//
// PRIVACY: everything here reports element *structure* and identifying attributes. It never
// reads `value`, `textContent`, or any user-entered data. Text is only ever measured by length.

import { deepQuerySelectorAll, isVisible } from './dom.js';

/** Attributes worth building a selector from, most stable first. */
export const STABLE_ATTRS = [
  'data-testid', 'data-test-id', 'data-test', 'data-cy', 'data-qa',
  'id', 'name', 'aria-label', 'placeholder', 'role',
];

/**
 * Attribute names that describe *state* rather than identity.
 *
 * `data-content-editable-root="true"` says what an element **is**; the
 * `data-content-editable-selecting="true"` beside it says what it is *doing right now*, and a
 * selector built on that resolves only while the user happens to be selecting. Both are
 * `data-` attributes with the value `true`, so only the name can tell them apart.
 */
const STATE_WORDS = [
  'selecting', 'selected', 'active', 'focused', 'focus', 'hover', 'hovered',
  'open', 'opened', 'expanded', 'collapsed', 'current', 'pending', 'loading',
  'disabled', 'checked', 'dragging', 'visible', 'hidden',
];

/**
 * Attribute names that could identify a *role*, whatever their values happen to hold.
 *
 * **The difference from `candidateAttributes` is the value check, and it is load-bearing.**
 * That function rejects an attribute whose value is a per-instance handle, which is correct
 * when naming one element: `[data-x="event_34s3…"]` matches that message and nothing else ever
 * again. But the same attribute with the value *dropped* – `[data-x]` – is exactly the role
 * marker we want, and `selectorForBoth` can only discover that if the element carrying it is
 * still in the running.
 *
 * It was not. Rejecting the value made Notion's answer container "unnameable", so
 * `chooseReplyElement` stopped preferring it and settled on a generic `div.xdt5ytf` – a
 * seven-character build-generated class matching twenty-four elements. The two fixes were
 * working against each other: one correctly refused a per-message value, and the other read
 * that refusal as "this element cannot be identified at all".
 *
 * So: names here, values in `candidateAttributes`. With two samples a value need not be stable,
 * which is the whole reason for recording two.
 */
export function roleAttributes(el) {
  const named = STABLE_ATTRS.filter((attr) => attr !== 'id' && el.getAttribute?.(attr));
  const discovered = [...(el.attributes ?? [])]
    .map((attr) => attr.name)
    .filter((name) => name.startsWith('data-') || name.startsWith('aria-'))
    .filter((name) => !STABLE_ATTRS.includes(name))
    // State, not identity – the same distinction `STATE_WORDS` already draws, and for the same
    // reason: `[data-loading]` names a moment, not a thing.
    .filter((name) => !STATE_WORDS.some((word) => name.includes(word)));

  return [...new Set([...named, ...discovered])];
}

/**
 * Every attribute on `el` worth trying, most intentional first.
 *
 * The fixed list above covers test ids, which are the most deliberate thing a team can leave
 * for us. But it was the *whole* list, and that turned out to be far too narrow: Notion's
 * assistant marks its answer container with `data-content-editable-root`, and because that
 * spelling was not enumerated, `selectorFor` fell all the way through to a structural path
 * matching 59 elements. A real app's semantic `data-` attributes cannot be enumerated in
 * advance – they have to be discovered.
 *
 * Values are filtered, not just names. `data-block-id="3d44bbb1-8f87-…"` is a UUID that changes
 * every answer; a selector built on it matches exactly one element and never matches again.
 */
function candidateAttributes(el) {
  const named = STABLE_ATTRS.filter((attr) => el.getAttribute?.(attr));

  const discovered = [...(el.attributes ?? [])]
    .map((attr) => attr.name)
    .filter((name) => name.startsWith('data-') && !STABLE_ATTRS.includes(name))
    .filter((name) => !STATE_WORDS.some((word) => name.includes(word)))
    .filter((name) => {
      const value = el.getAttribute(name);
      return value && !isGeneratedID(value);
    });

  return [...named, ...discovered];
}

/**
 * Whether an `id` was generated by a framework and will not survive a reload.
 *
 * **Found on the first real recording against Notion**, which produced `#\:rim\:` – a React
 * `useId()` value. It came from the `id` attribute, so it was recorded as *stable*, when it is
 * in fact among the least durable selectors on the page: `useId` numbers components by their
 * position in the render tree, so it changes on the next load or whenever that tree shifts.
 *
 * The failure this prevents is the expensive kind. A generated id resolves perfectly during the
 * dry run – the page has not reloaded yet – and the agent then breaks the first time the user
 * comes back to it, looking like vendor drift rather than a recording mistake.
 *
 * Rejecting one is cheap: the next attribute in `STABLE_ATTRS` is tried, and a structural path
 * is the floor. Being slightly over-eager here costs a less pretty selector; being under-eager
 * costs an agent that works once.
 */
export function isGeneratedID(value) {
  // React `useId()` – `:r0:`, `:rim:` – and anything wrapping it, such as Radix's
  // `radix-:r1:`. A colon is not legal in an author-written HTML id without escaping, so its
  // presence is close to proof of generation.
  if (value.includes(':')) return true;

  // Framework-assigned sequences: a known prefix, any number of word segments, and a trailing
  // counter – `mui-1`, `cdk-overlay-0`, `headlessui-menu-3`.
  //
  // Anchored at both ends deliberately. Requiring the id to *end* in digits is what keeps
  // `ng-container-title` and `chat-input` out of it: a counter at the end is the signature of
  // something assigned, while the same prefix followed by words is a name someone chose. An
  // earlier version matched only "prefix then digits" and let `cdk-overlay-0` through.
  if (/^(mui|cdk|ng|headlessui|react-aria|downshift|rc|chakra|mantine)(-[a-z]+)*[-_]?\d+$/i
    .test(value)) {
    return true;
  }

  // A bare number, or a UUID. Both are counters or handles, never names.
  if (/^\d+$/.test(value)) return true;
  if (/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value)) return true;

  // A high-entropy handle in any segment – `event_34s3k84bks4r9dp0t67t1t3hx7`.
  //
  // **Recorded live against Notion**, whose answer containers carry a per-message id. It is
  // worse than the `:rim:` case it joins, because it does not merely fail on the next page
  // load: it names *one message*, so the very next question matches nothing and every future
  // answer times out. Nothing upstream catches it – the reply's before/after count went 0→1
  // and reported PER-REPLY, which is exactly what a genuine per-reply container looks like on
  // a conversation that has one reply in it.
  //
  // The signal is entropy, not shape: sixteen-plus characters in one unbroken run, mixing
  // letters and digits. A name somebody chose that long puts separators between its words –
  // `agent-chat-send-button`, `content-editable-root` – so splitting first is what keeps those
  // out of it. Consistent with the policy above: over-eager costs a less pretty selector,
  // under-eager costs an agent that answers once and then never again.
  if (value.split(/[-_]/).some((segment) =>
    segment.length >= 16
      && /^[a-z0-9]+$/i.test(segment)
      && /[a-z]/i.test(segment)
      && /\d/.test(segment)
  )) {
    return true;
  }

  return false;
}

/**
 * How many elements match `selector`, counted the way the runtime counts.
 *
 * `document.querySelectorAll` stops at every shadow boundary, so on a page like LeanIX's –
 * 100+ shadow roots – it reports 0 matches for an element that plainly exists, the uniqueness
 * check fails, and a perfectly good `[data-testid=…]` is discarded in favour of a structural
 * path that cannot resolve from `document` either.
 */
export function deepMatchCount(selector) {
  try {
    return deepQuerySelectorAll(selector).length;
  } catch {
    return -1;                      // malformed selector
  }
}

/**
 * The most durable selector that identifies `el`.
 *
 * Returns the shape of `CapturedSelector` in `Sources/OpenPosseShared/Recording.swift` –
 * `{ css, via, isStable, matchCount }` – so neither side translates.
 */
export function selectorFor(el, { allowMultiple = false, forceStructural = false } = {}) {
  // `forceStructural` skips straight to the path, for `selectorForBoth` – which needs two
  // paths it can compare segment by segment, and an attribute selector for one element cannot
  // be compared with a structural path for the other.
  for (const attr of forceStructural ? [] : candidateAttributes(el)) {
    const value = el.getAttribute?.(attr);
    if (!value) continue;
    // A framework-generated id is worse than no id: it looks stable, resolves during the dry
    // run, and is gone by the next page load.
    if (attr === 'id' && isGeneratedID(value)) continue;

    const css = attr === 'id'
      ? `#${CSS.escape(value)}`
      : `${el.tagName.toLowerCase()}[${attr}="${CSS.escape(value)}"]`;

    // `allowMultiple` is what a *reply* element needs, and uniqueness is the wrong test for
    // one: a chat has one such element per turn, so requiring exactly one match rejects the
    // correct selector on every conversation after the first. Notion's answer container
    // matched 3 – one per answer so far – and was discarded for a structural path matching 59.
    //
    // The custom-element branch below has always made this allowance; the attribute branch
    // needed it too. A control (input, send button) still demands uniqueness, because two
    // matching send buttons means we do not know which one we would click.
    const matchCount = deepMatchCount(css);
    if (allowMultiple ? matchCount >= 1 : matchCount === 1) {
      return { css, via: attr, isStable: true, matchCount };
    }
  }

  // A custom element's tag name IS its identity.
  //
  // On a web-components app (Angular, Lit, Stencil) the semantic structure lives in tag names
  // like `lx-agentic-chat-assistant-message`, not in attributes. Checking only
  // `data-testid`/`id`/`aria-label` marks every one of those "unstable" and falls back to an
  // nth-of-type path – discarding the most durable selector on the page for the most brittle.
  // A component rename is far rarer than the class and DOM-shape churn a structural path
  // depends on.
  //
  // Deliberately allowed to match more than once: a chat has one such element per turn, and
  // the runtime takes the newest via `waitForNewMatch`. Uniqueness is the wrong test here.
  const tag = el.tagName.toLowerCase();
  if (!forceStructural && tag.includes('-')) {
    const matchCount = deepMatchCount(tag);
    if (matchCount >= 1) {
      return { css: tag, via: 'custom-element', isStable: true, matchCount };
    }
  }

  // Structural fallback: an nth-of-type path, always anchored.
  //
  // **It must reach an id or the document root.** A previous version capped the walk at six
  // segments, and on a deeply nested page that cap ended it partway – leaving a *relative*
  // path like `div:nth-of-type(1) > … ×6` that matches anywhere in the document. Measured on
  // Notion: 59 matches, and three different elements producing that identical selector. A
  // recipe built on it does not fail, which is the problem – `waitForNewMatch` takes the last
  // of the 59 and the agent reads out whatever that happens to be.
  //
  // The cap is now a safety limit rather than the usual exit, and anything that hits it is
  // reported honestly instead of being passed off as a path.
  const MAX_DEPTH = 20;
  const parts = [];
  let node = el;
  let anchored = false;

  while (node && node.nodeType === 1 && parts.length < MAX_DEPTH) {
    // Rooting the path at a generated id makes the whole selector expire on the next reload –
    // the same failure this path is meant to be the floor of.
    if (node.id && !isGeneratedID(node.id)) {
      parts.unshift(`#${CSS.escape(node.id)}`);
      anchored = true;
      break;
    }
    const parent = node.parentElement;
    if (!parent) { anchored = true; break; }        // reached the root: the path is absolute
    if (parent === document.body) {
      parts.unshift(`${node.tagName.toLowerCase()}:nth-of-type(\
${[...parent.children].filter((c) => c.tagName === node.tagName).indexOf(node) + 1})`);
      parts.unshift('body');
      anchored = true;
      break;
    }
    const siblings = [...parent.children].filter((c) => c.tagName === node.tagName);
    parts.unshift(`${node.tagName.toLowerCase()}:nth-of-type(${siblings.indexOf(node) + 1})`);
    node = parent;
  }

  const css = parts.join(' > ');
  const matchCount = deepMatchCount(css);
  return {
    css,
    // Names *why* it is weak, so the wizard can say something better than "fragile".
    via: anchored ? 'structure' : 'structure-unanchored',
    isStable: false,
    matchCount,
  };
}

/**
 * A selector that matches **both** recorded answers – the place answers appear, rather than
 * either of the two that happen to be there.
 *
 * **One sample cannot tell those apart, and everything that tried has been wrong.** Recorded
 * against Notion, a single answer produced `[data-agent-service-scroll-anchor="event_34s…"]`,
 * which named one message; with that rejected it produced a seventeen-segment `nth-of-type`
 * path, which named one *position*. Both matched perfectly at record time, both reported the
 * healthy-looking `0→1 PER-REPLY`, and both matched nothing on the very next question. There is
 * no test on a single element that separates "this answer" from "answers" – the distinction is
 * only visible across two.
 *
 * With two, it falls out: a selector that matches both cannot be naming either one.
 *
 * **Every strategy is tried and the tightest result wins**, rather than the first one that
 * works. That distinction cost a working setup. Notion marks *every* row –
 * questions, answers and a trailing seven-character one – with
 * `data-agent-service-find-row`, so the attribute strategy matched both answers and returned
 * immediately, naming a set three times too large. The runtime then took the last match, which
 * on Notion is not the answer, and the agent read a status message aloud.
 *
 * The right rule falls out of having two samples: the **smallest** set containing both answers
 * is the best description of "answers". A class only answers carry matches two; a row attribute
 * matches five or six. Ranking across strategies picks the class; ranking within one strategy
 * and returning early cannot.
 *
 * Order still breaks ties, because an attribute survives DOM churn better than a class and a
 * structural path is the floor – but only when the sets are the same size.
 */
export function selectorForBoth(a, b) {
  const matchesBoth = (css) => {
    if (!css) return false;
    const found = deepQuerySelectorAll(css);
    return found.includes(a) && found.includes(b);
  };

  /// Every selector that describes both, cheapest description last to break ties.
  const candidates = [];
  const consider = (css, via, isStable, rank) => {
    if (!matchesBoth(css)) return;
    candidates.push({ css, via, isStable, matchCount: deepMatchCount(css), rank });
  };

  // Either element's own best selector may already be general – a class or a `data-*` role
  // shared by every answer is exactly what we are hoping to find.
  for (const candidate of [a, b]) {
    const attempt = selectorFor(candidate, { allowMultiple: true });
    if (attempt.isStable) consider(attempt.css, attempt.via, true, 0);
  }

  // An attribute both answers carry, **whatever its value**.
  //
  // This is the case two samples exist to reveal, and it is the one Notion needs. Its answers
  // each have `data-agent-service-scroll-anchor`, with a different per-message id in it – so
  // the value is useless and the *name* is exactly the role marker we want. An attribute
  // present on two different answers is describing what they are; only its value distinguishes
  // them, which is precisely why dropping it generalises correctly.
  //
  // Unreachable from one sample: with a single element there is no way to tell an attribute
  // that marks every answer from one that marks this answer, and guessing wrong is what
  // produced a selector naming one message.
  if (a.tagName === b.tagName) {
    const tag = a.tagName.toLowerCase();
    for (const name of roleAttributes(a).filter((n) => b.hasAttribute?.(n))) {
      // Stable in the sense that matters: it survives a reload and names a role rather than
      // an instance.
      consider(`${tag}[${CSS.escape(name)}]`, `shared-attribute:${name}`, true, 1);

      // The attribute *with* its value, which is tighter whenever the value is a role rather
      // than a handle – `[data-role="assistant"]` on both answers beats `[data-role]` on every
      // row. Only when both carry the same value; a per-message id cannot match both, so this
      // costs nothing on the case that motivated dropping values in the first place.
      const value = a.getAttribute(name);
      if (value && b.getAttribute?.(name) === value) {
        consider(
          `${tag}[${CSS.escape(name)}="${CSS.escape(value)}"]`,
          `shared-attribute-value:${name}`, true, 1
        );
      }
    }
  }

  // A class both carry. Weaker than an attribute – class names churn on a redesign and are
  // often generated – but a class on *two different answers* is describing a role, and that is
  // the same argument as above. Still better than a positional path, which is the alternative.
  //
  // Not claimed stable: a class is the first thing a redesign changes, and the wizard should
  // keep saying so even when this is the tightest thing available.
  for (const name of [...(a.classList ?? [])]) {
    if (!b.classList?.contains(name) || isGeneratedID(name)) continue;
    consider(
      `${a.tagName.toLowerCase()}.${CSS.escape(name)}`, `shared-class:${name}`, false, 2
    );
  }

  // Tightest wins, and only then does the kind of selector break the tie. The smallest set
  // containing both answers is the best description of "answers" – that is the whole leverage
  // two samples provide, and returning the first strategy that worked threw it away.
  if (candidates.length > 0) {
    candidates.sort((x, y) => x.matchCount - y.matchCount || x.rank - y.rank);
    const { css, via, isStable, matchCount } = candidates[0];
    return { css, via, isStable, matchCount };
  }

  // Otherwise generalise the two structural paths against each other: keep the segments they
  // agree on, and drop the `:nth-of-type()` from those they do not. Where the two answers are
  // siblings, that is precisely the segment that names *which* one – so removing it turns
  // "the second child" into "any child", which is the set we are after.
  const pathA = structuralSegments(a);
  const pathB = structuralSegments(b);

  if (pathA.length === pathB.length && pathA.length > 0) {
    const merged = pathA.map((segment, index) =>
      segment === pathB[index] ? segment : segment.replace(/:nth-of-type\(\d+\)/, '')
    );
    const css = merged.join(' > ');
    if (matchesBoth(css)) {
      return {
        css,
        via: 'structure-generalised',
        // Still structural, so still the thing most likely to break on a redesign – and the
        // wizard says so. But it is at least structural about the *right* set.
        isStable: false,
        matchCount: deepMatchCount(css),
      };
    }
  }

  // Nothing describes both. Returning the first element's selector unchanged would hand back
  // the one-shot selector this function exists to prevent, so say so instead and let
  // `RecipeDraft` produce a sentence the user can act on.
  return null;
}

/**
 * Why two answers could not be described together – shape only, never content.
 *
 * `selectorForBoth` returning null was the second time in this project that a failure arrived
 * with nothing to diagnose it by. Tag names, counts and path depths are page *structure*, the
 * same category as a selector, so they are safe to write to the probe log and they are exactly
 * what says whether the recorder picked two analogous elements or two unrelated ones.
 */
export function describePair(a, b) {
  const sharedAttrs = [...(a.attributes ?? [])]
    .map((attr) => attr.name)
    .filter((name) => b.hasAttribute?.(name));
  const sharedClasses = [...(a.classList ?? [])]
    .filter((name) => b.classList?.contains(name));

  return [
    `tags=${a.tagName.toLowerCase()}/${b.tagName.toLowerCase()}`,
    a.tagName === b.tagName ? 'same-tag' : 'DIFFERENT-TAGS',
    `attrs=${a.attributes?.length ?? 0}/${b.attributes?.length ?? 0}`,
    `shared-attrs=${sharedAttrs.length}${sharedAttrs.length ? ` (${sharedAttrs.join(',')})` : ''}`,
    `shared-classes=${sharedClasses.length}`,
    `depth=${structuralSegments(a).length}/${structuralSegments(b).length}`,
    // The one that explains a bail-out on its own: the generaliser compares paths segment by
    // segment, so two answers sitting at different depths cannot be merged.
    `sameAncestor=${a.parentElement === b.parentElement ? 'siblings' : 'no'}`,
  ].join(' ');
}

/** The `nth-of-type` path as segments, so two of them can be compared. */
function structuralSegments(el) {
  const { css, via } = selectorFor(el, { allowMultiple: true, forceStructural: true });
  return via.startsWith('structure') ? css.split(' > ') : [];
}

/** Identifying attributes only – never `value`, never text. Used by the DevTools tool. */
export function describe(el) {
  const attrs = {};
  for (const attr of STABLE_ATTRS) {
    const value = el.getAttribute?.(attr);
    if (value) attrs[attr] = value;
  }
  return {
    tag: el.tagName.toLowerCase(),
    ...selectorFor(el),
    attrs,
    visible: isVisible(el),
    // Length only. The text itself is exactly what must never leave the page.
    textLength: (el.innerText ?? '').length,
  };
}
